/**
 * Get country rule by country name or code
 */
export function getCountryRule(countryNameOrCode: string): CountryRule {
  if (!countryNameOrCode) return COUNTRIES[0]; // UAE default
  const normalized = countryNameOrCode.trim().toLowerCase();

  const found = COUNTRIES.find(
    (c) =>
      c.code.toLowerCase() === normalized ||
      c.name.toLowerCase() === normalized ||
      (normalized === "uae" && c.code === "AE") ||
      (normalized === "ksa" && c.code === "SA") ||
      (normalized === "uk" && c.code === "GB") ||
      (normalized === "usa" && c.code === "US")
  );

  return found || COUNTRIES[COUNTRIES.length - 1]; // Fallback to OTHER
}
